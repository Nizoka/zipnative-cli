#!/usr/bin/env node
// @ts-check
/**
 * zipnative-cli — the tarball's file list, pinned (gate step `package-files`).
 *
 * Compares what `npm pack --dry-run --json` would publish with
 * docs/data/package-files.json: the same paths, nothing FORBIDDEN, and the
 * legal texts byte-identical (sha256). `--update` rewrites the manifest from
 * the current pack (review the diff: a new file in the tarball is a decision).
 *
 * Exit: 0 match · 1 drift · 2 usage / npm failure.
 */

import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PACKAGE_FILES_COMMAND, PACKAGE_FILES_MANIFEST, forbiddenReason, manifestEntries } from './lib/package-files.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const update = process.argv.includes('--update');
const unknown = process.argv.slice(2).filter((a) => a !== '--update');
if (unknown.length > 0) {
    process.stderr.write(`package-files: unknown argument ${unknown[0]}\nusage: node scripts/package-files.mjs [--update]\n`);
    process.exit(2);
}

// npm through its own CLI when the gate runs us (npm_execpath), else the shim.
const npmCli = process.env['npm_execpath'];
const r = npmCli !== undefined && existsSync(npmCli) && npmCli.endsWith('.js')
    ? spawnSync(process.execPath, [npmCli, 'pack', '--dry-run', '--json', '--ignore-scripts'], { cwd: ROOT, encoding: 'utf8' })
    : spawnSync('npm', ['pack', '--dry-run', '--json', '--ignore-scripts'], { cwd: ROOT, encoding: 'utf8', shell: process.platform === 'win32' });
if (r.status !== 0) {
    process.stderr.write(`package-files: npm pack --dry-run failed\n${r.stderr}`);
    process.exit(2);
}
/** @type {Array<{ files: Array<{ path: string }> }>} */
const report = JSON.parse(r.stdout);
const packed = report[0]?.files ?? [];
const readBytes = (/** @type {string} */ p) => (existsSync(join(ROOT, p)) ? readFileSync(join(ROOT, p)) : null);
const entries = manifestEntries(packed, readBytes);

/** @type {string[]} */
const failures = [];
for (const e of entries) {
    const why = forbiddenReason(e.path);
    if (why !== null) failures.push(`${e.path} must never ship: ${why}`);
}

const manifestPath = join(ROOT, PACKAGE_FILES_MANIFEST);
if (update) {
    if (failures.length > 0) {
        process.stderr.write(`package-files: refusing to bless a forbidden file:\n  ${failures.join('\n  ')}\n`);
        process.exit(1);
    }
    const doc = {
        $comment: 'Every file `npm pack` publishes, pinned. Generated by scripts/package-files.mjs — never hand-edited. role is derived from the path; sha256 is pinned for the legal texts only.',
        generatedBy: PACKAGE_FILES_COMMAND,
        files: entries,
    };
    writeFileSync(manifestPath, JSON.stringify(doc, null, 2) + '\n');
    process.stdout.write(`package-files: wrote ${PACKAGE_FILES_MANIFEST} (${entries.length} files)\n`);
    process.exit(0);
}

if (!existsSync(manifestPath)) {
    process.stderr.write(`package-files: ${PACKAGE_FILES_MANIFEST} is missing — run ${PACKAGE_FILES_COMMAND}\n`);
    process.exit(1);
}
/** @type {{ files: Array<{ path: string; role: string; sha256?: string }> }} */
const pinned = JSON.parse(readFileSync(manifestPath, 'utf8'));
const want = new Map(pinned.files.map((f) => [f.path, f]));
const got = new Map(entries.map((f) => [f.path, f]));
for (const [path] of got) if (!want.has(path)) failures.push(`${path} is packed but not pinned (a new file in the tarball is a decision: ${PACKAGE_FILES_COMMAND})`);
for (const [path] of want) if (!got.has(path)) failures.push(`${path} is pinned but no longer packed`);
for (const [path, f] of got) {
    const w = want.get(path);
    if (w === undefined) continue;
    if (w.role !== f.role) failures.push(`${path}: role ${f.role}, pinned ${w.role}`);
    if (w.sha256 !== undefined && w.sha256 !== f.sha256) failures.push(`${path}: the legal text changed (sha256 ${f.sha256 ?? 'missing'}, pinned ${w.sha256})`);
}

if (failures.length > 0) {
    process.stderr.write(`package-files: the tarball drifted from ${PACKAGE_FILES_MANIFEST}:\n  ${failures.join('\n  ')}\n`);
    process.exit(1);
}
process.stdout.write(`package-files: ${entries.length} files, as pinned\n`);
